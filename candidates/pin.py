#!/usr/bin/env python3
"""Explicitly refresh pinned GGUF revisions and generate candidate profiles."""
import argparse
import json
import re
import shlex
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAME = re.compile(r"cand-[a-z0-9]+(?:-[a-z0-9]+)*")


def model_files(siblings, quant):
    # Match the quant suffix, not auxiliary draft/projector files or a prefix quant.
    pattern = re.compile(r"-" + re.escape(quant) + r"(?:-\d{5}-of-\d{5})?\.gguf$")
    files = [s for s in siblings if pattern.search(Path(s["rfilename"]).name)
             and not any(part in s["rfilename"].lower()
                         for part in ("mmproj", "imatrix", "draft", "mtp", "lilicorr"))]
    if not files:
        raise ValueError(f"no main GGUF files for quant {quant}")
    files.sort(key=lambda s: s["rfilename"])
    names = [Path(s["rfilename"]).name for s in files]
    shards = [re.search(r"-(\d{5})-of-(\d{5})\.gguf$", n) for n in names]
    if any(shards):
        if not all(shards):
            raise ValueError("mixed sharded and single-file model")
        count = int(shards[0][2])
        if any(int(s[2]) != count for s in shards) or [int(s[1]) for s in shards] != list(range(1, count + 1)):
            raise ValueError("incomplete or duplicate model shards")
    elif len(files) != 1:
        raise ValueError("ambiguous main GGUF files")
    result = []
    for s in files:
        sha = s.get("lfs", {}).get("sha256", "")
        if not re.fullmatch(r"[a-f0-9]{64}", sha) or not s.get("size", 0):
            raise ValueError(f"missing LFS size/hash for {s['rfilename']}")
        result.append({"file": s["rfilename"], "bytes": s["size"], "sha256": sha})
    return result


def pin(catalog, existing, fetch):
    result = dict(existing)
    for name, spec in catalog.items():
        if not NAME.fullmatch(name):
            raise ValueError(f"invalid candidate ID: {name}")
        data = fetch(spec["repo"])
        revision = data["sha"]
        if not re.fullmatch(r"[a-f0-9]{40}", revision):
            raise ValueError("invalid revision")
        files = model_files(data["siblings"], spec["quant"])
        size = sum(f["bytes"] for f in files)
        if size > 90_000_000_000 and not spec.get("experimental"):
            raise ValueError(f"{name}: {size / 1e9:.1f} GB exceeds 90 GB cap")
        result[name] = {
            **spec, "revision": revision, "files": files, "bytes": size,
            "license": (data.get("cardData") or {}).get("license", "unknown"),
            "source_card": f"https://huggingface.co/{spec['repo']}/blob/{revision}/README.md",
        }
    return result


def profile(name, entry):
    ctx = entry.get("context", 131072)
    values = {
        "MODEL_FILE": "models/" + Path(entry["files"][0]["file"]).name,
        "ALIAS": "local-" + name, "CTX": str(ctx), "CACHE_K": "f16", "CACHE_V": "f16",
        "EXTRA_ARGS": entry["sampling"], "MIN_RAM_GB": "128",
        "DESC": entry["model"] + " " + entry["quant"] + " (candidate)",
    }
    if entry.get("template"):
        values["CHAT_TEMPLATE"] = entry["template"]
    return "# Generated by candidates/pin.py; candidate, not a production recommendation.\n" + "".join(
        f"{key}={shlex.quote(value)}\n" for key, value in values.items())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("names", nargs="*", help="Only refresh these IDs; otherwise all")
    args = parser.parse_args()
    catalog = json.loads((HERE / "catalog.json").read_text())
    if args.names:
        unknown = set(args.names) - catalog.keys()
        if unknown:
            parser.error(f"unknown candidates: {sorted(unknown)}")
        catalog = {name: catalog[name] for name in args.names}
    manifest = HERE / "manifest.json"
    existing = json.loads(manifest.read_text()) if manifest.exists() else {}

    def fetch(repo):
        print(f"Pinning {repo}", flush=True)
        with urllib.request.urlopen(f"https://huggingface.co/api/models/{repo}?blobs=true", timeout=60) as response:
            return json.load(response)

    entries = pin(catalog, existing, fetch)
    manifest.write_text(json.dumps(entries, indent=2) + "\n")
    (HERE / "profiles").mkdir(exist_ok=True)
    for name, entry in entries.items():
        (HERE / "profiles" / f"{name}.env").write_text(profile(name, entry))


if __name__ == "__main__":
    main()
